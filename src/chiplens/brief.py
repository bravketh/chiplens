"""One-page brief: a shareable Markdown summary of a scenario.

Built for the moment a product manager needs to paste a finding into a doc or
email: the verdict, the numbers, which upgrade helps, and how much of it rests on
guesses.
"""

from __future__ import annotations

from typing import Any

from chiplens.insight import Verdict
from chiplens.scenario import Result


def scenario_brief(
    chip: dict[str, Any],
    model: dict[str, Any],
    precision: str,
    result: Result,
    verdict: Verdict,
    sockets: int = 1,
    context_tokens: int = 0,
    upgrades: list[tuple[str, float, float]] | None = None,
) -> str:
    """Render a scenario as Markdown.

    Args:
        chip, model: Loaded data (names are used in the title).
        precision: Weight precision label.
        result: Output of ``scenario.analyze``.
        verdict: Output of ``insight.diagnose``.
        sockets: Chips used.
        context_tokens: Context per user, in tokens.
        upgrades: Optional (option, % change in per-user speed, % change in total
            throughput) rows.
    """
    r = result
    lines = [
        f"# {chip['name']} running {model['name']}",
        "",
        f"Scenario: {precision}, {sockets} chip(s), {r.batch} user(s), "
        f"{context_tokens:,} tokens of context each.",
    ]
    if r.tokens_per_read != 1.0 or r.efficiency != 1.0:
        lines.append(
            f"Adjustments: {r.tokens_per_read:g} tokens per weight read, "
            f"{r.efficiency:.0%} efficiency."
        )
    lines += [
        "",
        "## Finding",
        "",
        f"**{verdict.headline}**",
        "",
        verdict.detail,
        "",
        "What would help: " + "; ".join(verdict.levers) + ".",
        "",
        "## Numbers",
        "",
        "| Measure | Value |",
        "| --- | ---: |",
        f"| Speed per user | {r.per_user_tokens_per_s:,.1f} tokens/s |",
        f"| Total throughput | {r.system_tokens_per_s:,.0f} tokens/s |",
        f"| Compute in use | {r.compute_utilization:.1%} |",
        f"| Weights | {r.weights_gb:,.1f} GB |",
        f"| Power | {r.power_w:,.0f} W |",
        f"| Tokens per joule | {r.tokens_per_joule:.3f} |",
    ]
    if upgrades:
        lines += [
            "",
            "## Which upgrade helps",
            "",
            "| Option | Speed per user | Total throughput |",
            "| --- | ---: | ---: |",
        ]
        lines += [f"| {name} | {u:+.0f}% | {t:+.0f}% |" for name, u, t in upgrades]
    lines += [
        "",
        "## Inputs and how much to trust them",
        "",
        "| Input | Confidence |",
        "| --- | --- |",
    ]
    lines += [f"| {k} | {v} |" for k, v in sorted(r.used_inputs.items())]
    if r.assumed_inputs:
        lines += [
            "",
            "This finding leans on ASSUMED inputs: "
            + ", ".join(r.assumed_inputs)
            + ".",
        ]
    lines += [
        "",
        "---",
        "Generated by chiplens. An optimistic upper bound from a roofline model, "
        "not a measurement. Validation against published results is in "
        "validation/results.md.",
        "",
    ]
    return "\n".join(lines)
